    //--------
    // Vector
    //--------

    let v: Vec<i32> = Vec::new();

    //----------

    // If you create a Vec<T> with initial values, and Rust will infer the type of 
    // value you want to store
    let v = vec![1, 2, 3];

    //----------

    // If we want to be able to change its value, we need to make it mutable using 
    // the `mut` keyword

    // The numbers we place inside are all of type i32, and Rust infers this from the 
    // data, so we don’t need the Vec<i32> annotation

    let mut v = Vec::new();

    v.push(5);
    v.push(6);
    v.push(7);
    v.push(8);

    // A pop method removes and returns the last element
    v.pop();

    //----------

    // Using `&` and `[]` gives us a reference to the element at the index value

    let third: &i32 = &v[2];

    // ❌ You can’t have mutable and immutable references in the same scope
    // v.push(6);

    println!("The third element is {third}");

    // When we use the `get` method with the index passed as an argument, we get an 
    // `Option<&T>`

    let third: Option<&i32> = v.get(2);
    match third {
        Some(third) => println!("The third element is {third}"),
        None        => println!("There is no third element."),
    }

    //---------------------------------------
    // Iterating Over the Values in a Vector

    for i in &v {
        println!("{i}");
    }

    // Iterate over mutable references to each element in a mutable vector in order to 
    // make changes to all the elements

    for i in &mut v {
        *i += 50;
    }

    //---------------------------------------
    // Using an Enum to Store Multiple Types

    enum SpreadsheetCell {
        Int(i32),
        Float(f64),
        Text(String),
    }

    // Rust needs to know what types will be in the vector at compile time so that it 
    // knows exactly how much memory on the heap will be needed to store each element

    let row = vec![
        SpreadsheetCell::Int(3),
        SpreadsheetCell::Text(String::from("blue")),
        SpreadsheetCell::Float(10.12),
    ];

    //--------
    // String
    //--------

    let mut s = String::new();
    s.push_str("foo");

    // If we have some initial data with which we want to start the string, we use the 
    // `to_string` method,
    let data = "initial contents";
    let s = data.to_string();

    let s = "initial contents".to_string();

    // We can use the function `String::from` to create a String from a string literal
    let s = String::from("initial contents");

    //-------------------
    // Updating a string

    let mut s = String::from("foo");
    s.push_str("bar");
    s.push('l');

    println!("{s}");

    //----------------------
    // Concatenating with +

    let s1 = String::from("Hello, ");
    let s2 = String::from("world!");

    // The + operator uses the add method, whose signature looks something like this:
    //   fn add(self, s: &str) -> String {

    // 1. The signature of `add` takes ownership of `self` because `self` does not have
    //    an `&`. This means `s1` will be moved into the `add` call and will no longer 
    //    be valid after that
    // 2. `s2` has an `&`, meaning that we're adding a reference of the second string 
    //     to the first string

    let s3 = s1 + &s2; // Note: s1 has been moved here and can no longer be used
    println!("{s3}");

    //----------------------------
    // Concatenating with format!

    let s1 = String::from("Hello, ");
    let s2 = String::from("world!");

    // The code using `format!` is much easier to read, and the code generated by the 
    // `format!` macro uses references so that this call doesn’t take ownership of any 
    // of its parameters.

    let s3 = format!("{s1}{s2}");
    println!("{s3}");

    //-----------------------
    // Indexing into Strings

    // ❌ Rust strings don’t support indexing
    // let h = s3[0];

