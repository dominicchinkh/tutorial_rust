/*
 * 1. Given a list of integers, use a vector and return the median (when sorted, the value
 *    in the middle position) and mode (the value that occurs most often; a hash map will 
 *    be helpful here) of the list.
 */
pub fn median_and_mode(numbers: &[i32]) -> Option<(f64, i32)> {
    if numbers.is_empty() {
        return None;
    }

    // 1. Calculate Median
    // We clone the slice into a vector because we need to sort it, 
    // and we shouldn't mutate the original input slice.
    let mut sorted = numbers.to_vec();
    sorted.sort_unstable(); 

    let len = sorted.len();
    let mid = len / 2;
    
    let median = if len % 2 == 0 {
        // Average the two middle numbers if the length is even
        (sorted[mid - 1] as f64 + sorted[mid] as f64) / 2.0
    } else {
        // Otherwise, grab the exact middle
        sorted[mid] as f64
    };

    // 2. Calculate Mode
    let mut frequencies = HashMap::new();
    for &num in numbers {
        // or_insert(0) inserts 0 if the key doesn't exist, 
        // then returns a mutable reference to the value so we can add 1.
        *frequencies.entry(num).or_insert(0) += 1;
    }

    // Find the key with the highest value (count)
    let mode = frequencies

        // This converts the HashMap into an iterator. Because it's a map, the iterator 
        // yields each entry as a tuple containing the key and the value.
        .into_iter()

        // The closure `|&(_, count)|`: This takes a reference to the current tuple being 
        // evaluated. We use pattern matching to destructure it. The closure returns `count`

        // `max_by_key` returns an `Option` containing the entire winning tuple
        .max_by_key(|&(_, count)| count)

        // The closure `|(val, _)| val` ignores the count and returns just the value
        .map(|(val, _)| val)

        // We can safely unwrap here because we know the list isn't empty
        .unwrap(); 

    Some((median, mode))
}

/*
 * 2. Convert strings to Pig Latin. The first consonant of each word is moved to the end of 
 *    the word and ay is added, so first becomes irst-fay. Words that start with a vowel have
 *    hay added to the end instead (apple becomes apple-hay). Keep in mind the details about 
 *    UTF-8 encoding!
 */
fn is_vowel(c: char) -> bool {
    matches!(c, 'a' | 'e' | 'i' | 'o' | 'u' | 'A' | 'E' | 'I' | 'O' | 'U')
}

/// Converts a single word to Pig Latin.
pub fn convert_word(word: &str) -> String {
    let mut chars = word.chars();

    // Safely get the first character as a `char` (handles multi-byte UTF-8)
    let first_char = match chars.next() {
        Some(c) => c,
        None => return String::new(),
    };

    if is_vowel(first_char) {
        format!("{word}-hay")
    } else {
        // `chars.as_str()` returns a `&str` slice of all *remaining* characters.
        // Because it comes directly from the `Chars` iterator, it is guaranteed 
        // to land on a valid UTF-8 boundary.
        format!("{}-{}ay", chars.as_str(), first_char)
    }
}

/// Converts an entire sentence to Pig Latin.
pub fn to_pig_latin(text: &str) -> String {
    text.split_whitespace()
        .map(convert_word)
        .collect::<Vec<_>>()
        .join(" ")
}

/*
 * 3. Using a hash map and vectors, create a text interface to allow a user to add employee 
 *    names to a department in a company; for example, “Add Sally to Engineering” or “Add 
 *    Amir to Sales.” Then, let the user retrieve a list of all people in a department or all
 *    people in the company by department, sorted alphabetically.
 */
#[derive(Default)]
struct Company {
    // Map where Key = Department Name, Value = List of Employee Names
    departments: HashMap<String, Vec<String>>,
}

impl Company {

    // The `Self` keywords in the return type and in the body of the function are aliases for the type that appears
    // after the `impl` keyword
    fn new() -> Self {
        Self {
            departments: HashMap::new(),
        }
    }

    /// Adds an employee to a given department.
    fn add_employee(&mut self, name: &str, department: &str) {
        // `entry` gets or creates the key, `or_default` initializes an empty Vec
        self.departments
            .entry(department.to_string())
            .or_default()
            .push(name.to_string());
    }

    /// Returns a sorted vector of employee names for a specific department.
    fn get_department(&self, department: &str) -> Option<Vec<&str>> {
        self.departments.get(department).map(|employees| {
            let mut sorted: Vec<&str> = employees.iter().map(AsRef::as_ref).collect();
            sorted.sort_unstable();
            sorted
        })
    }

    /// Returns all departments and their employees, both sorted alphabetically.
    fn get_all(&self) -> Vec<(&str, Vec<&str>)> {
        let mut sorted_departments: Vec<&str> = self.departments.keys().map(AsRef::as_ref).collect();
        sorted_departments.sort_unstable();

        sorted_departments
            .into_iter()
            .map(|dept| {
                let mut employees: Vec<&str> =
                    self.departments[dept].iter().map(AsRef::as_ref).collect();
                employees.sort_unstable();
                (dept, employees)
            })
            .collect()
    }
}
